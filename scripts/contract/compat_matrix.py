"""Generate the 2.x compatibility matrix.

Rows come from the 2.x click tree (``slopvac.cli:main``), ``action.yml`` and
``.pre-commit-hooks.yaml``. Behaviour rows exist only in ``dispositions.toml``.
The hand-written dispositions supply the disposition, note and owner per row.

    uv run python scripts/contract/compat_matrix.py          # rewrite the files
    uv run python scripts/contract/compat_matrix.py --check  # exit 1 when stale
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

import click
import yaml

ROOT = Path(__file__).resolve().parents[2]
COMPAT = ROOT / "docs" / "contract" / "compat"
DISPOSITIONS = COMPAT / "dispositions.toml"
MATRIX_JSON = COMPAT / "matrix.json"
MATRIX_MD = COMPAT / "matrix.md"

VALID_DISPOSITIONS = ("preserve", "migrate", "remove-with-deprecation")
SOURCE_PREFIXES = ("cmd:", "opt:", "action:input:", "action:output:", "hook:")
BEHAVIOR_PREFIX = "behavior:"


def _param_row(command_path: str, param: click.Parameter) -> dict:
    is_arg = isinstance(param, click.Argument)
    key = param.name if is_arg else max(param.opts, key=len)
    detail = {"kind": "argument" if is_arg else "option"}
    if isinstance(param.type, click.Choice):
        detail["choices"] = list(param.type.choices)
    if not is_arg and getattr(param, "is_flag", False):
        detail["flag"] = True
    return {
        "id": f"opt:{command_path}:{key}",
        "source": "click",
        "summary": " ".join([*param.opts, *param.secondary_opts]) or str(param.name),
        "detail": detail,
    }


def click_rows() -> list[dict]:
    from slopvac.cli import main

    rows: list[dict] = []

    def walk(command: click.Command, path: str) -> None:
        rows.append({"id": f"cmd:{path}", "source": "click", "summary": f"slopvac {path}".replace("slopvac root", "slopvac"), "detail": {}})
        for param in command.params:
            rows.append(_param_row(path, param))
        if isinstance(command, click.Group):
            for name, sub in command.commands.items():
                walk(sub, name if path == "root" else f"{path} {name}")

    walk(main, "root")
    return rows


def action_rows() -> list[dict]:
    data = yaml.safe_load((ROOT / "action.yml").read_text(encoding="utf-8"))
    rows = []
    for name, spec in data.get("inputs", {}).items():
        rows.append({"id": f"action:input:{name}", "source": "action.yml", "summary": name, "detail": {"default": spec.get("default")}})
    for name in data.get("outputs", {}):
        rows.append({"id": f"action:output:{name}", "source": "action.yml", "summary": name, "detail": {}})
    return rows


def hook_rows() -> list[dict]:
    hooks = yaml.safe_load((ROOT / ".pre-commit-hooks.yaml").read_text(encoding="utf-8"))
    return [{"id": f"hook:{h['id']}", "source": ".pre-commit-hooks.yaml", "summary": h["entry"], "detail": {}} for h in hooks]


def load_dispositions() -> dict[str, dict]:
    return tomllib.loads(DISPOSITIONS.read_text(encoding="utf-8"))


def source_rows() -> list[dict]:
    return click_rows() + action_rows() + hook_rows()


def build() -> list[dict]:
    """Merge source rows and behaviour rows with their dispositions."""
    table = load_dispositions()
    rows = source_rows()
    for key, entry in table.items():
        if key.startswith(BEHAVIOR_PREFIX):
            rows.append({"id": key, "source": "behavior", "summary": entry.get("summary", ""), "detail": {}})
    for row in rows:
        entry = table.get(row["id"], {})
        row["disposition"] = entry.get("disposition", "")
        row["note"] = entry.get("note", "")
        row["owner"] = entry.get("owner", "")
        row["test"] = "pending" if row["disposition"] == "preserve" else "n/a"
    return sorted(rows, key=lambda r: r["id"])


def render_json(rows: list[dict]) -> str:
    return json.dumps({"schema": "slopvac-compat-matrix/1", "rows": rows}, indent=2, ensure_ascii=False) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_md(rows: list[dict]) -> str:
    counts: dict[str, int] = {}
    for row in rows:
        counts[row["disposition"]] = counts.get(row["disposition"], 0) + 1
    lines = [
        "<!-- Generated by scripts/contract/compat_matrix.py. Do not edit. -->",
        "",
        "# 2.x compatibility matrix",
        "",
        "Totals: " + ", ".join(f"{k or 'unset'} {v}" for k, v in sorted(counts.items())) + f", {len(rows)} rows.",
        "",
        "| Row | Disposition | 3.0 note | Owner | Test |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append(f"| `{_cell(r['id'])}` | {r['disposition']} | {_cell(r['note'])} | {r['owner']} | {r['test']} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed files are stale")
    args = parser.parse_args(argv)
    rows = build()
    outputs = {MATRIX_JSON: render_json(rows), MATRIX_MD: render_md(rows)}
    if args.check:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
